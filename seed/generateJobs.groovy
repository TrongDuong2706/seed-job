/*
 * Creates one Pipeline job for every pipeline entry prepared by the seed
 * Jenkinsfile. The Jenkinsfile validates and parses YAML with Pipeline Utility
 * Steps before this Job DSL script runs.
 *
 * Job DSL receives a JSON file, avoiding YAML parser classpath differences.
 */

import groovy.json.JsonSlurper

def pipelineConfigs = new JsonSlurper().parseText(readFileFromWorkspace('seed/pipelines.json'))

def generated = 0

println "Prepared ${pipelineConfigs.size()} pipeline entries."

pipelineConfigs.findAll { pipelineConfig ->
    if (!pipelineConfig.name || !pipelineConfig.jenkinsfilePath) {
        println "Skip invalid pipeline entry from ${pipelineConfig.seedSource ?: 'unknown source'}: ${pipelineConfig}"
        return false
    }
    return true
}.each { pipelineConfig ->
        def source = pipelineConfig.seedSource ?: 'unknown source'

        pipelineJob(pipelineConfig.name) {
            description("""Generated by seedjob from ${source}.
Application repository: ${pipelineConfig.appRepo ?: 'not configured'}
Kind: ${pipelineConfig.kind ?: 'Pipeline'}""")

            logRotator {
                numToKeep(30)
                daysToKeep(30)
            }

            definition {
                cpsScm {
                    scm {
                        git {
                            remote {
                                url(centralRepoUrl)
                                if (centralRepoCredentialsId) {
                                    credentials(centralRepoCredentialsId)
                                }
                            }
                            branch("*/${centralRepoBranch}")
                        }
                    }
                    scriptPath(pipelineConfig.jenkinsfilePath)
                    lightweight()
                }
            }
        }

        println "Generated Pipeline job: ${pipelineConfig.name}"
        generated++
}

if (generated == 0) {
    throw new IllegalStateException('No pipeline jobs were generated. Check the parsed config entries printed above.')
}


