/*
 * Creates one Pipeline job for every pipeline entry in:
 *   centralized-jenkins-file/<application>/config.yaml
 *
 * YAML is parsed with the SnakeYAML API bundled with Jenkins rather than a
 * hand-written indentation parser.
 */

def configuredCentralRepoUrl = (centralRepoUrl ?: '').toString().trim()
def configuredCentralRepoCredentialsId = (centralRepoCredentialsId ?: '').toString().trim()
def configuredCentralRepoBranch = (centralRepoBranch ?: 'main').toString().trim()

if (!configuredCentralRepoUrl) {
    throw new IllegalArgumentException('CENTRAL_REPO_URL must not be empty.')
}

def configFiles = [
    'centralized-jenkins-file/todolist/config.yaml',
    'centralized-jenkins-file/crm/config.yaml',
    'centralized-jenkins-file/ecommerce/config.yaml'
]

def generated = 0

configFiles.each { configFile ->
    def yaml = readFileFromWorkspace(configFile)
    if (!yaml?.trim()) {
        println "Skip ${configFile}: file is empty or does not exist."
        return
    }

    def pipelineConfigs = parsePipelines(yaml)
    println "Parsed ${pipelineConfigs.size()} pipeline entries from ${configFile}: ${pipelineConfigs}"

    pipelineConfigs.findAll { pipelineConfig ->
        if (!pipelineConfig.name || !pipelineConfig.jenkinsfilePath) {
            println "Skip invalid pipeline entry in ${configFile}: ${pipelineConfig}"
            return false
        }
        return true
    }.each { pipelineConfig ->

        pipelineJob(pipelineConfig.name) {
            description("""Generated by seedjob from ${configFile}.
Application repository: ${pipelineConfig.appRepo ?: 'not configured'}
Kind: ${pipelineConfig.kind ?: 'Pipeline'}""")

            logRotator {
                numToKeep(30)
                daysToKeep(30)
            }

            definition {
                cpsScm {
                    scm {
                        git {
                            remote {
                                url(configuredCentralRepoUrl)
                                if (configuredCentralRepoCredentialsId) {
                                    credentials(configuredCentralRepoCredentialsId)
                                }
                            }
                            branch("*/${configuredCentralRepoBranch}")
                        }
                    }
                    scriptPath(pipelineConfig.jenkinsfilePath)
                    lightweight()
                }
            }
        }

        println "Generated Pipeline job: ${pipelineConfig.name}"
        generated++
    }
}

if (generated == 0) {
    throw new IllegalStateException('No pipeline jobs were generated. Check the parsed config entries printed above.')
}

/** Parse `pipelines` as a list of maps using Jenkins' bundled SnakeYAML API. */
List<Map<String, String>> parsePipelines(String yaml) {
    def document = new org.yaml.snakeyaml.Yaml().load(yaml)
    if (!(document instanceof Map) || !(document.pipelines instanceof List)) {
        return []
    }

    return document.pipelines.collect { entry ->
        if (!(entry instanceof Map)) {
            return [:]
        }
        entry.collectEntries { key, value ->
            [(key.toString()): value == null ? '' : value.toString()]
        }
    }
}

